// Regenerates src/features/hero/scene/still.ts: the scene's final frame for reduced motion, so that
// path never downloads the engine. Run against `npm run dev`: node scripts/hero-still.mjs [url]
import { writeFileSync } from "node:fs";
import { chromium } from "playwright";

const SEED = 2;
const url = process.argv[2] ?? "http://localhost:3000";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto(`${url}/?seed=${SEED}`);
await p.waitForFunction(() => window.__hero?.ep);
const html = await p.evaluate(() => {
  const h = window.__hero;
  h.seek(h.ep.MAIN + 2.2); // the frame the prototype shows when it can't animate
  const stage = document.querySelector("[data-engine] .stage").cloneNode(true);
  // the cursors live in their own layer (above the turbo key); the still has no key, so fold them in
  const overlay = stage.querySelector(".overlay");
  for (const c of document.querySelectorAll("[data-engine] .stage.cursors > *"))
    overlay.appendChild(c.cloneNode(true));
  const hidden = (e) =>
    e.getAttribute("opacity") === "0" ||
    e.style.opacity === "0" ||
    e.style.display === "none";
  for (const e of [...stage.querySelectorAll("*")])
    if (stage.contains(e) && hidden(e)) e.remove();
  stage.querySelector("[data-el=measure]")?.remove();
  // git log messages are translated: keep the key and the episode's names, fill them per locale
  for (const c of stage.querySelectorAll(".glog .c[data-k]"))
    c.lastElementChild.textContent = `{L:${c.dataset.k}:${c.dataset.v ?? ""}}`;
  for (const e of stage.querySelectorAll("*"))
    for (const a of [...e.attributes])
      if (a.name.startsWith("data-")) e.removeAttribute(a.name);
  stage.querySelector(".chip.ok .txt").textContent = "{deployed}";
  stage.querySelector(".cursor.fb .name").textContent = "{fb}";
  return stage.outerHTML.replace(/>\s+</g, "><");
});
await b.close();
writeFileSync(
  "src/features/hero/scene/still.ts",
  `/* Generated by scripts/hero-still.mjs (seed ${SEED}) — the scene's final frame, drawn by the engine. */
import type { HeroDict } from "./engine";

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => \`&#\${c.charCodeAt(0)};\`);
const STILL = ${JSON.stringify(html)};

const log = (d: HeroDict, k: string, v: string) => {
  const [a = "", b = "", l = "", n = ""] = v.split("|"), o: Record<string, string> = { a, b, l, n };
  return d.log[k as keyof HeroDict["log"]].replace(/\\{(\\w+)\\}/g, (_, x) => o[x] ?? "");
};

export const stillHTML = (d: HeroDict) =>
  STILL.replace("{deployed}", esc(d.deployed))
    .replace("{fb}", esc(d.fb))
    .replace(/\\{L:(\\w+):([^}]*)\\}/g, (_, k, v) => esc(log(d, k, v)));
`,
);
console.log("still.ts", html.length, "chars");
